import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { CASES } from "../suites/nda-boundary/cases.mjs";
import { signature, score } from "../engine/mine.mjs";
import { wilson, mcnemarExact, krippendorffAlphaNominal, fmt } from "./stats.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const suite = join(here, "..", "suites", "nda-boundary");
const REVIEWERS = ["opus-plain", "opus-cfl", "sonnet-plain", "haiku-system"];
const LABEL = {
  "opus-plain": "Claude Opus 5.5, playbook only",
  "opus-cfl": "Claude Opus 5.5, Claude for Legal NDA Triager",
  "sonnet-plain": "Claude Sonnet 5.5, playbook only",
  "haiku-system": "Claude Haiku 5.5 with courtproof tools",
};

const load = (cond, arm) => JSON.parse(readFileSync(join(suite, "answers", cond, `${arm}.json`), "utf8"));
const answers = cond => Object.fromEntries(REVIEWERS.map(r => [r, Object.fromEntries(load(cond, r).runs.flat().map(x => [x.case, x.answer]))]));
const before = answers("before"), after = answers("after");
const ids = split => CASES.filter(c => c.split === split).map(c => c.id);
const key = id => CASES.find(c => c.id === id).key;
const keySig = id => `${key(id).classification}|${[...key(id).issues].sort().join(",")}`;

// 1. Edge NDAs, wording A: agreement among the reviewers, and with the stipulated key.
const edge = ids("mine").map(id => {
  const sigs = REVIEWERS.map(r => signature(before[r][id]));
  return { id, sigs, unanimous: new Set(sigs).size === 1, matchesKey: sigs.filter(s => s === keySig(id)).length };
});
const edgeUnanimous = edge.filter(e => e.unanimous).length;
const edgeAllMatch = edge.filter(e => e.unanimous && e.matchesKey === REVIEWERS.length).length;
const alphaEdge = krippendorffAlphaNominal(edge.map(e => e.sigs));

// 2. Held-out wordings (B) and controls, per reviewer, before and after the two rulings.
const exactIds = (ans, list) => list.filter(id => score(ans[id], key(id)).exact);
const per = REVIEWERS.map(r => {
  const test = ids("test"), ctrl = ids("control");
  const tb = new Set(exactIds(before[r], test)), ta = new Set(exactIds(after[r], test));
  const b = test.filter(id => !tb.has(id) && ta.has(id)).length; // wrong before, right after
  const c = test.filter(id => tb.has(id) && !ta.has(id)).length; // right before, wrong after
  return {
    reviewer: r,
    heldOutBefore: tb.size, heldOutAfter: ta.size, heldOutN: test.length,
    mcnemar: { improved: b, worsened: c, p: mcnemarExact(b, c) },
    controlsBefore: exactIds(before[r], ctrl).length, controlsAfter: exactIds(after[r], ctrl).length, controlsN: ctrl.length,
  };
});
const alphaOn = data => krippendorffAlphaNominal([...ids("test"), ...ids("control")].map(id => REVIEWERS.map(r => signature(data[r][id]))));
const alphaBefore = alphaOn(before), alphaAfter = alphaOn(after);
const pct = x => `${Math.round(x * 100)} %`;
const a = x => (x === null ? "undefined (one reading only)" : x.toFixed(2));

const L = [
  "# Pilot study — re-analysis with uncertainty",
  "",
  "Generated by `node analysis/pilot.mjs` from the answers committed on 2 November 2026. No model was run again.",
  "Intervals are 95 % Wilson intervals; paired before/after comparisons use the exact McNemar test.",
  "",
  "## What the pilot can and cannot say",
  "",
  "- **Ten questions, one run per reviewer and condition, four configurations of one provider (Anthropic).** The four reviewers are not independent: they share a provider and, for three of them, the same playbook text.",
  "- **The key is stipulated.** The \"team's position\" on each question was fixed by the author acting as a fictional General Counsel, before the first run; it was not validated by independent lawyers. On P1 and P2 the reviewers' reading is defensible; the pilot shows that they all read the playbook the same way, and differently from one stated intention — not that they are wrong in law.",
  "- **The keys were committed locally before the runs** (commits 1016822, a9b6fc0, b24726a, all on 2 November 2026, pushed to GitHub the same evening). Local commit dates can be set by anyone; the next study is registered publicly before any run.",
  "",
  "## 1. Edge NDAs (wording A): agreement among reviewers and with the stipulated key",
  "",
  `- Unanimous readings: ${fmt(edgeUnanimous, edge.length)}. Krippendorff's alpha among the four reviewers: ${a(alphaEdge)}.`,
  `- Unanimous and equal to the stipulated key: ${fmt(edgeAllMatch, edge.length)}.`,
  `- Unanimous and different from the stipulated key: ${edge.filter(e => e.unanimous && e.matchesKey === 0).map(e => e.id).join(", ") || "none"}.`,
  "",
  "## 2. Held-out wordings (B), before and after two rulings",
  "",
  "| Reviewer | Before | After | Changed (better / worse) | Exact McNemar p |",
  "|---|---|---|---|---|",
  ...per.map(x => `| ${LABEL[x.reviewer]} | ${fmt(x.heldOutBefore, x.heldOutN)} | ${fmt(x.heldOutAfter, x.heldOutN)} | ${x.mcnemar.improved} / ${x.mcnemar.worsened} | ${x.mcnemar.p.toFixed(2)} |`),
  "",
  "The same two questions (P1, P2) changed for every reviewer. With two changed pairs, no reviewer's improvement is statistically established (p = 0.50); the result is a signal for the next study, not a finding.",
  "",
  "## 3. Controls and guards (5 NDAs)",
  "",
  "| Reviewer | Before | After |",
  "|---|---|---|",
  ...per.map(x => `| ${LABEL[x.reviewer]} | ${fmt(x.controlsBefore, x.controlsN)} | ${fmt(x.controlsAfter, x.controlsN)} |`),
  "",
  `Agreement among reviewers on the 15 held-out and control NDAs: Krippendorff's alpha ${a(alphaBefore)} before the rulings, ${a(alphaAfter)} after.`,
  "",
  "## 4. Sample size for the next study",
  "",
  `With 40 questions, a proportion of 0.80 has a 95 % interval of about ${pct(wilson(32, 40)[0])}–${pct(wilson(32, 40)[1])}; with 10 it is ${pct(wilson(8, 10)[0])}–${pct(wilson(8, 10)[1])}. Study A therefore plans at least 40 questions, read by at least five lawyers and four model families, three runs each (see PROTOCOL.md).`,
  "",
];
writeFileSync(join(here, "PILOT.md"), L.join("\n"));
writeFileSync(join(here, "pilot.json"), JSON.stringify({ edge, edgeUnanimous, edgeAllMatch, alphaEdge, per, alphaBefore, alphaAfter }, null, 2) + "\n");
console.log(L.join("\n"));
